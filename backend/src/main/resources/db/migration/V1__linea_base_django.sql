-- Línea base del esquema: EXACTAMENTE el que produce Django.
--
-- Generada con `pg_dump --schema-only --no-owner --no-privileges` sobre una
-- base con todas las migraciones de `clinube` aplicadas (Django 5.2.17,
-- PostgreSQL 16). Se regenera con `scripts/regenerar-linea-base.sh`.
--
-- Se conservan TODAS las tablas, incluidas `django_migrations`,
-- `django_content_type`, `auth_permission`, `auth_group*`, `django_session`
-- y `django_admin_log`. No es descuido:
--
--   · `accounts_user_groups` y `accounts_user_user_permissions` existen
--     porque el User de Django hereda de PermissionsMixin, y tienen claves
--     foráneas a `auth_group` y `auth_permission`, que a su vez apunta a
--     `django_content_type`. Quitarlas rompería esas restricciones.
--   · El objetivo del punto 2 del plan es poder cambiar un servidor por el
--     otro sin migrar datos, y el comparador del punto 9 arranca los DOS
--     servidores contra copias de la misma base. Sin `django_migrations`,
--     Django no vuelve a arrancar contra ella.
--
-- Hibernate corre en modo `validate`: el esquema lo manda este archivo, no
-- las entidades. Si una entidad y esta línea base no coinciden, el servidor
-- no arranca, que es justo lo que se quiere.
--
-- Lo único que se le quita al volcado son las instrucciones que solo
-- entiende `psql` (\restrict, \unrestrict) y la cabecera de SET, que
-- pondría `search_path` a vacío y dejaría a Flyway sin poder escribir su
-- propia tabla de historial.

